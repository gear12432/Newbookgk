export function getTranslation(key: TranslationKey, langNameOrCode: string = 'English'): string {
  // Find language code by name or code
  const langItem = SUPPORTED_LANGUAGES.find(
    (l) => l.code === langNameOrCode.toLowerCase() || l.name.toLowerCase() === langNameOrCode.toLowerCase()
  );

  const code = langItem ? langItem.code : 'en';

  if (translations[code] && translations[code][key]) {
    return translations[code][key]!;
  }

  // Fallback to English
  return translations['en'][key] || key;
}
